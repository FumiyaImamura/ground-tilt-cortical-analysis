def equal_limits_regional(points: np.ndarray) -> list[tuple[float, float, np.ndarray]]:
    points = np.asarray(points, dtype=float)
    spans = [max(float(np.ptp(points[:, dim])), 1.0) for dim in range(3)]
    common = max(spans) * 1.04
    locator = MaxNLocator(nbins=4, steps=[1, 2, 2.5, 5, 10])
    output = []
    for dim in range(3):
        midpoint = 0.5 * (float(np.min(points[:, dim])) + float(np.max(points[:, dim])))
        low, high = midpoint - 0.5 * common, midpoint + 0.5 * common
        ticks = np.asarray(locator.tick_values(low, high), dtype=float)
        ticks = ticks[(ticks >= low) & (ticks <= high)]
        if ticks.size < 2:
            ticks = np.asarray([low, high])
        output.append((low, high, ticks))
    return output


def plane_aligned_view(points: np.ndarray) -> tuple[float, float, float]:
    centered = points - points.mean(axis=0, keepdims=True)
    _, eigenvectors = np.linalg.eigh(np.cov(centered, rowvar=False))
    normal = eigenvectors[:, 0]
    if normal[2] < 0:
        normal = -normal
    elevation = float(np.degrees(np.arcsin(np.clip(normal[2], -1, 1))))
    azimuth = float(np.degrees(np.arctan2(normal[1], normal[0])) % 360)
    return elevation, azimuth, 0.0


def style_figure_6a_grid(ax: plt.Axes, target_divisor: float = 12.0) -> None:
    """Match the refined Figure 6a grid without changing the saved view."""

    ax.patch.set_visible(False)
    limits = np.asarray([ax.get_xlim3d(), ax.get_ylim3d(), ax.get_zlim3d()], dtype=float)
    span = float(np.max(np.abs(np.diff(limits, axis=1))))
    target = span / target_divisor
    power = 10.0 ** np.floor(np.log10(target))
    choices = power * np.asarray([1.0, 2.0, 2.5, 5.0, 10.0])
    step = float(choices[np.argmin(np.abs(np.log(choices / target)))])
    for pc, (axis, (low, high)) in enumerate(
        zip((ax.xaxis, ax.yaxis, ax.zaxis), limits), start=1
    ):
        ticks = step * np.arange(np.ceil(low / step), np.floor(high / step) + 1)
        ticks[np.isclose(ticks, 0.0)] = 0.0
        labelled = {0, len(ticks) - 1, int(np.argmin(np.abs(ticks)))}
        axis.set_ticks(ticks)
        axis.set_ticklabels([f"{value:g}" if index in labelled else "" for index, value in enumerate(ticks)])
        axis.pane.set_facecolor("white")
        axis.pane.set_edgecolor("none")
        axis.pane.set_linewidth(0.0)
        axis.pane.set_alpha(1.0)
        axis._axinfo["grid"].update(color="0.65", linewidth=0.30, linestyle="-")
        axis.set_label_text(f"PC{pc}", fontsize=6.5)
        axis.labelpad = -2.0
    ax.set_xlim3d(*limits[0])
    ax.set_ylim3d(*limits[1])
    ax.set_zlim3d(*limits[2])


