def jumping_mean(data: np.ndarray, axis: int, num_to_combine: int) -> np.ndarray:
    """Match the interleaved trial grouping used by the original helper."""

    data = np.asarray(data)
    step_size = int(np.round(data.shape[axis] / num_to_combine))
    means = []
    for start in range(step_size):
        indices = np.arange(start, data.shape[axis], step_size, dtype=int)
        means.append(np.take(data, indices, axis=axis).mean(axis=axis))
    return np.stack(means, axis=axis)


def circular_colors(values: np.ndarray) -> np.ndarray:
    indices = np.rint(255 * np.mod(values, 2 * np.pi) / (2 * np.pi)).astype(int)
    return plt.get_cmap("hsv")(np.linspace(0, 1, 256))[indices]


def scalar_colors(
    values: np.ndarray,
    minimum_maximum: tuple[float, float] | None = None,
    code_direction: bool = False,
) -> np.ndarray:
    values = np.asarray(values, dtype=float).copy()
    if minimum_maximum is None:
        low, high = float(np.nanmin(values)), float(np.nanmax(values))
    else:
        low, high = map(float, minimum_maximum)
    values = np.clip(values, low, high)
    scaled = (values - low) / (high - low)
    if code_direction:
        delta = np.diff(scaled, axis=1)
        delta = np.concatenate((delta, delta[:, -1:]), axis=1)
        scaled[delta < 0] *= -1
        scaled = (scaled + 1) / 2
    indices = np.rint(255 * scaled).astype(int)
    return plt.get_cmap("hsv")(np.linspace(0, 1, 256))[indices]


def trajectory_points(values: np.ndarray, field: str, n_trials: int) -> np.ndarray:
    axis = 1 if field == "p8" else 0
    averaged = jumping_mean(values, axis=axis, num_to_combine=n_trials)
    return averaged.reshape(-1, averaged.shape[-1])


def trajectory_segments(
    values: np.ndarray,
    stimulus: np.ndarray,
    field: str,
    n_trials: int,
) -> tuple[np.ndarray, np.ndarray]:
    if field == "p8":
        averaged = jumping_mean(values, axis=1, num_to_combine=n_trials)
        segments = np.stack(
            (averaged[:, :, :-1, :].reshape(-1, 3), averaged[:, :, 1:, :].reshape(-1, 3)),
            axis=1,
        )
        direction = jumping_mean(stimulus[:, :, :, 0], axis=1, num_to_combine=n_trials)
        modal = stats.mode(direction, axis=2, keepdims=True).mode
        direction = np.broadcast_to(modal, direction.shape)
        colors = circular_colors(direction[:, :, :-1]).reshape(-1, 4)
        return segments, colors

    averaged = jumping_mean(values, axis=0, num_to_combine=n_trials)
    segments = np.stack(
        (averaged[:, :-1, :].reshape(-1, 3), averaged[:, 1:, :].reshape(-1, 3)),
        axis=1,
    )
    if field == "rot":
        colors = circular_colors(stimulus[:, 1:, 0])
        colors = jumping_mean(colors, axis=0, num_to_combine=n_trials).reshape(-1, 4)
    else:
        parameter_index = {"tilt": 0, "zvert": 5, "yaw": 2}[field]
        parameter = jumping_mean(
            stimulus[:, 1:, parameter_index], axis=0, num_to_combine=n_trials
        )
        colors = scalar_colors(
            parameter,
            minimum_maximum=(0, 2 * np.pi) if field == "tilt" else None,
            code_direction=field in ("zvert", "yaw"),
        ).reshape(-1, 4)
    return segments, colors


def limits_and_ticks(points: np.ndarray) -> list[tuple[float, float, np.ndarray]]:
    points = np.asarray(points, dtype=float)
    spans = [
        max(float(np.nanmax(points[:, dim]) - np.nanmin(points[:, dim])), 1.0)
        for dim in range(3)
    ]
    common = max(spans)
    output = []
    for dim in range(3):
        midpoint = 0.5 * (float(np.nanmin(points[:, dim])) + float(np.nanmax(points[:, dim])))
        low = midpoint - 0.5 * common
        high = midpoint + 0.5 * common
        pad = 0.02 * common
        axis_low, axis_high = low - pad, high + pad
        locator = MaxNLocator(nbins=6, steps=[1, 2, 2.5, 5, 10])
        ticks = np.asarray(locator.tick_values(axis_low, axis_high), dtype=float)
        ticks = ticks[(ticks >= axis_low) & (ticks <= axis_high)]
        if ticks.size < 2:
            ticks = np.asarray([axis_low, axis_high])
        output.append((axis_low, axis_high, ticks))
    return output


def endpoint_zero_formatter(ticks: np.ndarray) -> FuncFormatter:
    ticks = np.asarray(ticks, dtype=float)

    def format_tick(value: float, _position: int) -> str:
        keep = np.isclose(value, ticks[0]) or np.isclose(value, ticks[-1])
        if np.any(np.isclose(ticks, 0.0)):
            keep = keep or np.isclose(value, 0.0)
        return f"{value:g}" if keep else ""

    return FuncFormatter(format_tick)


def depth_sort_callback(ax: plt.Axes, segments: np.ndarray, colors: np.ndarray, collection: Line3DCollection):
    def callback(event) -> None:
        if event.canvas.figure is not ax.figure:
            return
        from mpl_toolkits.mplot3d import proj3d

        midpoints = segments.mean(axis=1)
        _, _, z_values = proj3d.proj_transform(
            midpoints[:, 0], midpoints[:, 1], midpoints[:, 2], ax.get_proj()
        )
        order = np.argsort(z_values)[::-1]
        collection.set_segments(segments[order])
        collection.set_color(colors[order])

    return callback


def draw_3d_trajectory(
    ax: plt.Axes,
    values: np.ndarray,
    stimulus: np.ndarray,
    field: str,
    n_trials: int,
    linewidth: float = 1.05,
) -> None:
    segments, colors = trajectory_segments(values, stimulus, field, n_trials)
    collection = Line3DCollection(segments, linewidths=linewidth, alpha=1, colors=colors)
    try:
        ax.add_collection3d(collection, autolim=False)
    except TypeError:
        # Matplotlib before 3.8 has no ``autolim`` argument. Every caller sets
        # explicit 3-D limits immediately afterwards, so both branches are
        # numerically and visually equivalent.
        ax.add_collection3d(collection)
    ax.figure.canvas.mpl_connect(
        "draw_event", depth_sort_callback(ax, segments, colors, collection)
    )


def style_3d_axis(
    ax: plt.Axes,
    title: str,
    panel_letter: str,
    limits: list[tuple[float, float, np.ndarray]],
) -> None:
    for setter, (low, high, ticks) in zip(
        (ax.set_xlim3d, ax.set_ylim3d, ax.set_zlim3d), limits
    ):
        setter(low, high)
    ax.set_xticks(limits[0][2])
    ax.set_yticks(limits[1][2])
    ax.set_zticks(limits[2][2])
    ax.xaxis.set_major_formatter(endpoint_zero_formatter(limits[0][2]))
    ax.yaxis.set_major_formatter(endpoint_zero_formatter(limits[1][2]))
    ax.zaxis.set_major_formatter(endpoint_zero_formatter(limits[2][2]))
    ax.set_xlabel("PC1", labelpad=-8)
    ax.set_ylabel("PC2", labelpad=0)
    ax.set_zlabel("PC3", labelpad=0)
    ax.tick_params(axis="x", pad=0, length=2, width=0.5)
    ax.tick_params(axis="y", pad=5, length=2, width=0.5)
    ax.tick_params(axis="z", pad=2, length=2, width=0.5)
    ax.view_init(elev=10, azim=80, roll=0)
    ax.set_box_aspect((1, 1, 1))
    ax.set_title(title, pad=1.5, fontweight="normal")
    ax.text2D(
        0.01, 0.99, panel_letter, transform=ax.transAxes,
        ha="left", va="top", fontsize=11, fontweight="bold"
    )
    for axis in (ax.xaxis, ax.yaxis, ax.zaxis):
        axis._axinfo["grid"].update(
            {"linewidth": 0.45, "linestyle": "-", "color": (0.68, 0.68, 0.68, 1)}
        )
        axis._axinfo["axisline"].update({"linewidth": 0.65, "color": (0, 0, 0, 1)})
        axis.pane.set_facecolor((1, 1, 1, 1))
        axis.pane.set_edgecolor((0.7, 0.7, 0.7, 1))


