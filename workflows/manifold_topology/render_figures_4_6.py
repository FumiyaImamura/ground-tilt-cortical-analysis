def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def sem(values: np.ndarray, axis: int | None = None) -> np.ndarray:
    values = np.asarray(values, dtype=float)
    n = np.sum(np.isfinite(values), axis=axis)
    return np.nanstd(values, axis=axis, ddof=1) / np.sqrt(np.maximum(n, 1))


def bonferroni(values: list[float] | np.ndarray) -> np.ndarray:
    values = np.asarray(values, dtype=float)
    return np.minimum(1.0, values * values.size)


def stars(p_value: float) -> str:
    for threshold, label in ((1e-3, "***"), (1e-2, "**"), (5e-2, "*")):
        if p_value < threshold:
            return label
    return "n.s."


def ptext(p_value: float) -> str:
    for exponent in range(8, 2, -1):
        if p_value < 10.0 ** (-exponent):
            return rf"$p<10^{{-{exponent}}}$"
    return rf"$p={p_value:.3g}$"


