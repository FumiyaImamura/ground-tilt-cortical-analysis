def draw_motion_key(ax: plt.Axes, field: str, label: str) -> None:
    ax.set_xlim(-1.25, 1.25)
    ax.set_ylim(-1.35, 1.35)
    ax.set_aspect("equal")
    ax.axis("off")
    if field in ("rot", "p8"):
        angle = np.linspace(0, 2 * np.pi, 80, endpoint=False)
        ax.scatter(
            np.cos(angle), np.sin(angle), c=plt.get_cmap("hsv")(angle / (2 * np.pi)),
            s=7, linewidths=0,
        )
        if field == "rot":
            for start in (0.35 * np.pi, 1.35 * np.pi):
                ax.annotate(
                    "", xy=(0.78 * np.cos(start + 0.55), 0.78 * np.sin(start + 0.55)),
                    xytext=(0.78 * np.cos(start), 0.78 * np.sin(start)),
                    arrowprops=dict(arrowstyle="->", color="k", lw=0.65, connectionstyle="arc3,rad=0.22"),
                )
        else:
            for start in np.linspace(0, 2 * np.pi, 8, endpoint=False):
                ax.annotate(
                    "", xy=(0.83 * np.cos(start), 0.83 * np.sin(start)), xytext=(0, 0),
                    arrowprops=dict(arrowstyle="->", color="k", lw=0.55),
                )
        ax.text(0, -1.28, label, ha="center", va="top", fontsize=7.5)
    else:
        ax.text(0, 0, label, ha="center", va="center", fontsize=7.5)


def draw_scale_bar(ax: plt.Axes, half_range: float, bar_length: float) -> None:
    padding = 0.08 * bar_length
    ax.set_xlim(0, bar_length + 2 * padding)
    ax.set_ylim(-half_range, half_range)
    ax.set_aspect("equal", adjustable="box")
    ax.set_anchor("W")
    ax.axis("off")
    x0, x1 = padding, padding + bar_length
    y0 = -0.73 * half_range
    ax.plot([x0, x0, x1], [y0 + bar_length, y0, y0], color="k", lw=0.85, clip_on=False)
    ax.text((x0 + x1) / 2, y0 - 0.09 * half_range, f"{bar_length:g} S.D.", ha="center", va="top", fontsize=6.5)


