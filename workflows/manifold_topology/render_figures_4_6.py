def band(ax: plt.Axes, x: np.ndarray, values: np.ndarray, color: str, label: str | None = None):
    mean = np.nanmean(values, axis=1)
    error = sem(values, axis=1)
    ax.plot(x, mean, "-", lw=1.4, color=color, label=label)
    ax.fill_between(x, mean - error, mean + error, color=color, alpha=0.30, lw=0)
    return mean, error


def log_slopes(values: np.ndarray) -> np.ndarray:
    output = np.full(values.shape[1], np.nan)
    for column in range(values.shape[1]):
        response = np.log(values[:, column] + 1e-300)
        valid = np.isfinite(response)
        if valid.sum() > 2:
            output[column] = np.polyfit(W2[valid], response[valid], 1)[0]
    return output


